#!/usr/bin/env node
// Generates src/icons.jsx from the Threadmark brand icon set (24px grid, 1.5px stroke, round caps).
// Usage: node scripts/build-icons.mjs <path-to-brand-assets/icons>
// Each icon becomes a tree-shakable component that draws in currentColor. Stroke weight follows the
// brand rule for small sizes: 24px 1.5, 18-22px 1.25, 16px 1.125, 12-14px 1 (non-scaling strokes).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/build-icons.mjs <brand-assets/icons>");
  process.exit(1);
}

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const icons = [];
for (const group of readdirSync(source).sort()) {
  const dir = join(source, group);
  if (!statSync(dir).isDirectory()) continue;
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
    const svg = readFileSync(join(dir, file), "utf8");
    const paths = [];
    // Every drawing element becomes [tag, geometry, strokeFactor]; a factor of 0 means filled.
    const GEOMETRY = { path: ["d"], rect: ["x", "y", "width", "height", "rx", "ry"], circle: ["cx", "cy", "r"], ellipse: ["cx", "cy", "rx", "ry"], line: ["x1", "y1", "x2", "y2"], polyline: ["points"], polygon: ["points"] };
    for (const match of svg.matchAll(/<(path|rect|circle|ellipse|line|polyline|polygon)\b([^>]*?)\/?>/g)) {
      const [, tag, attrs] = match;
      const geometry = {};
      for (const name of GEOMETRY[tag]) {
        const value = new RegExp(`\\s${name}="([^"]+)"`).exec(attrs)?.[1];
        if (value != null) geometry[name] = value;
      }
      if (!Object.keys(geometry).length) continue;
      const width = Number(/stroke-width="([\d.]+)"/.exec(attrs)?.[1] || 1.5);
      const filled = /fill="#/.test(attrs) && !/stroke="/.test(attrs);
      paths.push([tag, geometry, filled ? 0 : Math.round((width / 1.5) * 100) / 100]);
    }
    icons.push({ name: `${pascal(basename(file, ".svg"))}Icon`, group, file, paths });
  }
}

// Two shapes the product needs that the brand set draws only inside a circle.
icons.push({ name: "CheckIcon", group: "extra", file: "check", paths: [["path", { d: "M5 12.5L10 17.5L19 7" }, 1]] });
icons.push({ name: "SpinnerIcon", group: "extra", file: "spinner", paths: [["path", { d: "M20.5 12A8.5 8.5 0 1 1 12 3.5" }, 1]] });

const lines = [
  "// Generated by scripts/build-icons.mjs from the Threadmark brand icon set. Do not edit by hand.",
  'import { createElement } from "react";',
  "",
  "// Brand rule: strokes thin out as icons shrink so small icons don't look heavy.",
  "export function iconStroke(size) {",
  "  if (!size) return undefined;",
  "  if (size >= 24) return 1.5;",
  "  if (size >= 18) return 1.25;",
  "  if (size >= 16) return 1.125;",
  "  return 1;",
  "}",
  "",
  "function makeIcon(displayName, paths) {",
  "  function Icon({ size, strokeWidth, className, style, ...rest }) {",
  "    const base = strokeWidth ?? iconStroke(size);",
  "    return createElement(",
  '      "svg",',
  "      {",
  '        viewBox: "0 0 24 24",',
  '        fill: "none",',
  '        stroke: "currentColor",',
  '        strokeLinecap: "round",',
  '        strokeLinejoin: "round",',
  "        width: size,",
  "        height: size,",
  "        className,",
  '        style: base ? { ...style, "--tm-icon-stroke": base } : style,',
  "        ...rest,",
  "      },",
  "      paths.map(([tag, geometry, factor], index) => createElement(tag, factor",
  "        ? { key: index, ...geometry, vectorEffect: \"non-scaling-stroke\", style: { strokeWidth: `calc(var(--tm-icon-stroke, 1.25px) * ${factor})` } }",
  '        : { key: index, ...geometry, fill: "currentColor", stroke: "none" })),',
  "    );",
  "  }",
  "  Icon.displayName = displayName;",
  "  return Icon;",
  "}",
  "",
];
for (const icon of icons) {
  lines.push(`/** ${icon.group}/${icon.file} */`);
  lines.push(`export const ${icon.name} = /*#__PURE__*/ makeIcon(${JSON.stringify(icon.name)}, ${JSON.stringify(icon.paths)});`);
}
const out = fileURLToPath(new URL("../src/icons.jsx", import.meta.url));
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`Wrote ${icons.length} icons to ${out}`);
